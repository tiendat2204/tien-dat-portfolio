import Image from 'next/image'
import Link from 'next/link'

import { Icon } from '@/components/Icon'
import { Icons } from '@/components/icons'
import { Status, StatusIndicator, StatusLabel } from '@/components/kibo-ui/status'
import { GITHUB_REPO, SITE_INFO } from '@/data/config'
import { DATA } from '@/data/resume'
import registry from '@/__registry__/registry.autogenerated.json'
import pkg from '../../package.json'

const REPO_URL = `https://github.com/${GITHUB_REPO}`
const STACK = [
  { name: 'next', icon: 'nextjs-icon.svg' },
  { name: 'react', icon: 'react-icon.svg' },
  { name: 'tailwindcss', icon: 'tailwindcss-icon.svg' },
  { name: 'motion', icon: 'motiondev-icon.svg' },
  { name: 'typescript', icon: 'typescript-icon.svg' },
] as const

function version (name: string) {
  const deps: Record<string, string> = { ...pkg.dependencies, ...pkg.devDependencies }
  return deps[name]?.replace(/^[\^~]/, '')
}

function ExternalLink ({ href, children }: { href: string; children: React.ReactNode }) {
  return (
    <a
      href={href}
      target='_blank'
      rel='noreferrer'
      className='underline decoration-dotted underline-offset-4 transition-colors hover:text-foreground hover:decoration-solid'
    >
      {children}
    </a>
  )
}

// One manifest line: key, dotted leader, value.
function Row ({ k, children }: { k: string; children: React.ReactNode }) {
  return (
    <div className='flex items-baseline gap-2'>
      <dt className='shrink-0 text-muted-foreground'>{k}</dt>
      <span aria-hidden='true' className='min-w-4 flex-1 -translate-y-[3px] border-b border-dotted border-border' />
      <dd className='shrink-0 text-right'>{children}</dd>
    </div>
  )
}

